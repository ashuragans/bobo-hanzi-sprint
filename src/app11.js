const PUN = /[，。？！、：；「」（）]/;
function tokenizeZh(str) {
  const toks = []; let i = 0;
  while (i < str.length) {
    const c = str[i];
    if (PUN.test(c)) { toks.push([c, '']); i++; continue; }
    if (!HAN.test(c)) { i++; continue; }
    let L = Math.min(6, str.length - i), hit = null;
    for (; L >= 1; L--) { const sub = str.slice(i, i + L); if ([...sub].every(ch => HAN.test(ch)) && (OVR[sub] || H2W[sub] || (L > 1 && /^[零一二兩三四五六七八九十百千萬]+$/.test(sub)))) { hit = sub; break; } }
    if (!hit) { hit = c; L = 1; }
    i += L;
    let py = null;
    if (str[i] === '{') { const j = str.indexOf('}', i); py = str.slice(i + 1, j); i = j + 1; }
    toks.push([hit, py ?? pyOf(hit), py != null]);
    if (py != null) { const alt = WL.find(w => w.h === hit && plainPy(w.p) === plainPy(py)); if (alt) toks[toks.length - 1].push(alt.k); }
  }
  toks.forEach((x, k) => { const nx = toks[k + 1]; if (x[2] || !nx || !nx[1]) return; const nt = nx[0] === '個' ? 4 : firstTone(nx[1]); if (x[0] === '不') x[1] = nt === 4 ? 'bú' : 'bù'; if (x[0] === '一') x[1] = nt === 4 ? 'yí' : 'yì'; });
  tokenizeZh.keys = toks.map(x => x[3] || (H2W[x[0]] && H2W[x[0]].k)).filter(Boolean);
  return toks.map(x => [x[0], x[1]]);
}
EXAMPLES.forEach(([zh, en], i) => {
  const toks = tokenizeZh(zh);
  const keys = uniq(tokenizeZh.keys);
  const ls = keys.flatMap(k => W[k].ls.filter(l => l in LIDX)).map(l => LIDX[l]);
  const s = { id: 'ex-' + i, toks, en, L: ls.length ? 'L' + Math.max(...ls) : 'L6', src: 'ex', zh: plainZh(toks), keys };
  SENTS.push(s); keys.forEach(k => (SIDX[k] = SIDX[k] || []).push(s));
});
